// Computes the decimals of pi with Machin's formula and writes src/data/pi.ts.
// pi = 16·arctan(1/5) − 4·arctan(1/239), in BigInt fixed point.
import { writeFileSync } from "node:fs";

const DIGITS = 10000;
const GUARD = 20n;
const scale = 10n ** (BigInt(DIGITS) + GUARD);

function arctanInv(x) {
  const x2 = x * x;
  let term = scale / x;
  let sum = term;
  for (let k = 1n; term !== 0n; k++) {
    term /= x2;
    sum += (k % 2n ? -term : term) / (2n * k + 1n);
  }
  return sum;
}

const pi = (16n * arctanInv(5n) - 4n * arctanInv(239n)) / 10n ** GUARD;
const decimals = pi.toString().slice(1, DIGITS + 1);
if (!decimals.startsWith("14159265358979323846264338327950288419716939937510")) {
  throw new Error("pi digits failed the sanity check");
}
writeFileSync(
  new URL("../src/data/pi.ts", import.meta.url),
  `// Generated by scripts/gen-pi.mjs. The first ${DIGITS} decimals of pi (after "3.").\nexport const PI_DECIMALS =\n  "${decimals}";\n`,
);
console.log(`wrote ${decimals.length} decimals, ends …${decimals.slice(-10)}`);
